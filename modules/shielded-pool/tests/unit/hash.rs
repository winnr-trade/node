use shielded_pool::hash::poseidon_t3;

#[test]
fn poseidon_t3_matches_known_vector() {
    let mut a = [0u8; 32];
    let mut b = [0u8; 32];
    a[31] = 1;
    b[31] = 2;

    // poseidon(1n, 2n) == 7853200120776062878684798364095072458815029376092732009249414926327459813530n
    let expected: [u8; 32] = [
        0x11, 0x5c, 0xc0, 0xf5, 0xe7, 0xd6, 0x90, 0x41, 0x3d, 0xf6, 0x4c, 0x6b, 0x96, 0x62,
        0xe9, 0xcf, 0x2a, 0x36, 0x17, 0xf2, 0x74, 0x32, 0x45, 0x51, 0x9e, 0x19, 0x60, 0x7a,
        0x44, 0x17, 0x18, 0x9a,
    ];

    assert_eq!(poseidon_t3(&a, &b), expected);
}
